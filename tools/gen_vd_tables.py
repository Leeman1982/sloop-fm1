"""Videodrome: the tables of the six component models (firmware/src/vd_parts.c), written to
firmware/src/vd_tables.h (checked in; tests/run_tests.sh checks it is up to date).

    python3 tools/gen_vd_tables.py [OUT]

The cutoff scale is SLOOP's own (tools/gen_tables.py CUTOFF_HZ: 30 Hz .. 16 kHz over 0..127), in 1/256 of a step
(u = value << 8), extended both ways for the modulation: u from -64 << 8 (~1.4 Hz) to 160 << 8 (the 0.45 FS clamp).
The tables have a point every half step (u >> 7) and are read with linear interpolation."""
import math
import sys

FS = 44100
U_LO = -64          # in whole steps of the cutoff knob
U_HI = 160
N = (U_HI - U_LO) * 2 + 1


def fc_of(step):
    f = 30.0 * ((16000 / 30) ** (step / 127))
    return min(f, 0.45 * FS)


def arr(name, ctype, vals, per=12):
    out = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")
    return out


def main():
    out_path = sys.argv[1] if len(sys.argv) > 1 else "firmware/src/vd_tables.h"
    L = ["/* SPDX-License-Identifier: GPL-3.0-only */",
         "/* Videodrome component-model tables. Generated by tools/gen_vd_tables.py: do not edit. */",
         "#pragma once",
         "#include <stdint.h>",
         f"#define VD_U_LO ({U_LO * 256})          /* the lowest cutoff the tables hold, SLOOP cutoff units */",
         f"#define VD_U_HI ({U_HI} << 8)",
         f"#define VD_GN {N}"]
    steps = [U_LO + i / 2 for i in range(N)]
    # impulse-invariant one-pole: y += G (x - y), G = 1 - e^(-2 pi fc / FS), Q15 (the nonlinear explicit stages:
    # a difference of two Q15 tanh values times G stays inside 32 bits)
    L += arr("VD_GEXP", "uint16_t", [min(32767, int(round(32768 * (1 - math.exp(-2 * math.pi * fc_of(s) / FS)))))
                                     for s in steps])
    # trapezoidal integrator gain g = tan(pi fc / FS), Q16 (the state-variable and Sallen-Key stages)
    L += arr("VD_GTAN", "uint32_t", [int(round(65536 * math.tan(math.pi * fc_of(s) / FS))) for s in steps], 8)
    # tanh over -4 .. 4 (x Q15), a point every 1/64, Q15 out: the transistor and OTA stages
    L += arr("VD_TANH", "int16_t", [int(round(32767 * math.tanh((i - 256) / 64))) for i in range(513)])
    with open(out_path, "w") as f:
        f.write("\n".join(L) + "\n")
    print(f"vd tables: {N} cutoff points, 513 tanh points -> {out_path}")


if __name__ == "__main__":
    main()
