"""The RP2350 build's boot wordmark: VIDEODROME as an XBM for the 128 x 64 OLED (U8g2 drawXBM), from the repository's
own Terminus (assets/fonts/ter-u16b.bdf, as tools/gen_vd_splash.py), bent sideways a scanline at a time as the film's
title card arrives (a slight wobble, one tear), with xtro's slits (rows cleared across the bottom, as its CARPENTER SYNTH
wordmark). Not bold: at 128 x 64 a doubled column closes the counters. Deterministic.
  tools/gen_oled_wordmark.py rp2350/Videodrome/vd_wordmark.h"""
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
from gen_vd_splash import BDF, bdf_glyphs  # noqa: E402

WORD = "VIDEODROME"
SLITS = (12, 14)                          # rows of the 16 cleared after drawing (low: the letters still read)


def wordmark():
    g = bdf_glyphs(BDF)
    w = sum(g[c][0] for c in WORD) + 6              # + room for the bend both ways
    h = 16
    img = [[0] * w for _ in range(h)]
    x = 3
    for c in WORD:
        cw, rows = g[c]
        for r, bits in enumerate(rows):
            for k, b in enumerate(bits):
                if b == "1":
                    img[r][x + k] = 1
        x += cw
    out = [[0] * w for _ in range(h)]
    for y in range(h):
        bend = int(round(0.6 * math.sin(y / 3.1) + (1 if y in (6, 7) else 0)))   # the wobble, and one tear
        for xx in range(w):
            if img[y][xx] and 0 <= xx + bend < w:
                out[y][xx + bend] = 1
    for y in SLITS:
        out[y] = [0] * w
    return w, h, out


def xbm(path):
    w, h, img = wordmark()
    data = []
    for row in img:
        for b0 in range(0, w, 8):
            v = 0
            for k in range(8):
                if b0 + k < w and row[b0 + k]:
                    v |= 1 << k                  # XBM: the leftmost pixel is bit 0
            data.append(v)
    lines = ["/* generated by tools/gen_oled_wordmark.py: VIDEODROME for the OLED (U8g2 drawXBM); do not edit */",
             "#pragma once", "#include <stdint.h>", f"#define VD_WORD_W {w}", f"#define VD_WORD_H {h}",
             f"static const uint8_t VD_WORD_BITS[{len(data)}] = {{"]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{v:02X}" for v in data[i:i + 16]) + ",")
    lines.append("};")
    Path(path).write_text("\n".join(lines) + "\n")
    print(f"wordmark: {w} x {h} -> {path}")


if __name__ == "__main__":
    xbm(sys.argv[1] if len(sys.argv) > 1 else ROOT / "rp2350" / "Videodrome" / "vd_wordmark.h")
